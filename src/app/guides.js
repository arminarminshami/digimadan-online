// کلید راهنمای هر صفحه از روی آدرس
export function guideKeyForPath(pathname, search = '') {
  if (pathname === '/admin') return 'adminHome'
  if (pathname === '/admin/ads') return 'adminAds'
  if (pathname === '/') return 'home'
  if (pathname === '/ads') return 'ads'
  if (pathname === '/app/services') return 'services'
  if (pathname === '/app/post-ad') return 'postad'
  if (pathname === '/auctions') return 'auctions'
  if (pathname === '/prices') return 'prices'
  if (pathname === '/dashboard' && !new URLSearchParams(search).get('tab')) return 'account'
  return null
}
