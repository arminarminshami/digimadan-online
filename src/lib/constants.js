// ------------------------------------------------------------
// انتخاب فیلترِ «نوع» متناسب با دسته‌بندی انتخاب‌شده
// ------------------------------------------------------------
// هر دسته‌بندی فهرست نوع مخصوص خودش را دارد؛ مثلا در «معادن» باید
// فهرست انواع معدن (معدن کلسیت، معدن مس و...) نمایش داده شود نه فهرست
// مواد معدنی خام. مقدار ذخیره‌شده در دیتابیس یکسان می‌ماند و فقط
// برچسبِ نمایشی فرق می‌کند، تا فیلتر روی داده‌های موجود هم کار کند.
//
// خروجی: { param, label, placeholder, groups } یا null اگر آن دسته
// اصلا فیلترِ نوع لازم نداشته باشد (مثل مشارکت و اکتشاف/استخراج).
// مرتب‌سازی الفبایی فارسی. localeCompare با 'fa' ترتیب درست حروف فارسی
// (مثلا آ قبل از ا، و پ/چ/ژ/گ در جای درست) را رعایت می‌کند.
export function sortFa(items) {
  return [...items].sort((a, b) => {
    const av = typeof a === 'string' ? a : a.label
    const bv = typeof b === 'string' ? b : b.label
    return String(av).localeCompare(String(bv), 'fa')
  })
}

// نسخه‌ی مرتب‌شده‌ی گروه‌ها (اقلام داخل هر گروه الفبایی می‌شوند)
function sortGroups(groups) {
  return groups.map((g) => ({ ...g, items: sortFa(g.items) }))
}

export const MINERAL_GROUPS_SORTED = sortGroups(MINERAL_GROUPS)
export const MACHINE_GROUPS_SORTED = sortGroups(MACHINE_GROUPS)

export function getTypeFilterConfig(category) {
  if (category === 'mining_machinery') {
    return {
      param: 'machineType',
      label: 'نوع ماشین‌آلات',
      placeholder: 'نوع ماشین‌آلات (همه)',
      groups: MACHINE_GROUPS_SORTED,
    }
  }

  if (category === 'mines') {
    return {
      param: 'mineralType',
      label: 'نوع معدن',
      placeholder: 'نوع معدن (همه)',
      // مقدار همان نام ماده معدنی است (چون در دیتابیس همین ذخیره می‌شود)
      // ولی متن نمایشی «معدن ...» است.
      groups: MINERAL_GROUPS_SORTED.map((g) => ({
        ...g,
        items: g.items.map((m) => ({ value: m, label: `معدن ${m}` })),
      })),
    }
  }

  if (SIMPLE_AD_CATEGORIES.includes(category)) return null

  // پیش‌فرض: مواد معدنی (و حالتی که هیچ دسته‌ای انتخاب نشده)
  return {
    param: 'mineralType',
    label: 'نوع ماده معدنی',
    placeholder: 'نوع ماده معدنی (همه)',
    groups: MINERAL_GROUPS_SORTED,
  }
}

// گزینه‌های یک گروه را به شکل یکدست {value,label} برمی‌گرداند
export function normalizeTypeItems(items) {
  return items.map((it) => (typeof it === 'string' ? { value: it, label: it } : it))
}
